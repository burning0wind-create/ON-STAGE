function chooseProfile(target) {
  const exact=DIRECTION_PROFILES[target.programId]?.[target.directionId];
  if(exact)return {key:exact,basis:'已选目录专业与研究方向'};
  const direction=String(target.direction??'').trim();
  // Custom targets can use an explicitly supplied direction label; never infer
  // a specialism from a college name or from a resume/portfolio keyword.
  const tests=[
    [/人工智能与数据设计|数据设计|数据驱动设计/,'data_design'],
    [/设计历史|设计史|艺术设计史|设计理论|史论/,'history'],
    [/美术创作|艺术理论|信息艺术研究|影视创作/,'art'],
    [/工业设计与数智交叉|互动媒体设计与技术|互联网\+创新设计|信息技术|艺术与科技/,'technology'],
    [/服务体系|服务系统|设计战略|管理与创业/,'service'],
    [/交互|体验设计/,'interaction'],
    [/环境设计|空间设计|城市更新|展示设计/,'environment'],
    [/染织|服装|服饰|陶瓷|工艺|紫砂|材料设计/,'craft'],
    [/工业设计|产品设计|产品战略/,'product'],
    [/视觉|传达|媒体|媒介|动画|广告传播|公共艺术|科普艺术|文化数字化/,'visual'],
  ];
  if(direction)for(const [pattern,key] of tests)if(pattern.test(direction))return {key,basis:'明确填写的研究方向名称'};
  const code=String(target.majorCode??'');
  if(CODE_PROFILES[code])return {key:CODE_PROFILES[code],basis:'已选专业代码；未进一步细分方向'};
  const major=String(target.major??'').trim();
  if(/工业设计工程|机械/.test(major))return {key:'product',basis:'自定义专业名称'};
  if(/设计学/.test(major))return {key:'research',basis:'自定义设计学专业；方向未细分'};
  if(/艺术学|美术/.test(major))return {key:'art',basis:'自定义艺术相关专业'};
  if(/设计/.test(major))return {key:'practice',basis:'自定义设计专业；方向未细分'};
  return {key:'research',basis:'目标尚未细分，采用通用设计研究标准'};
}

